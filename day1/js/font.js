const PixelFont = {
  cache: {},

  // Returns a 6x7 canvas for the glyph in the given color (cached).
  glyph(ch, color) {
    const key = ch + color;
    if (this.cache[key]) return this.cache[key];
    const cols = FONT_GLYPHS[ch] || FONT_GLYPHS['?'];
    const c = document.createElement('canvas');
    c.width = 6;
    c.height = 7;
    const g = c.getContext('2d');
    g.fillStyle = color;
    for (let x = 0; x < 5; x++) {
      for (let y = 0; y < 7; y++) {
        if (cols[x] & (1 << y)) g.fillRect(x, y, 1, 1);
      }
    }
    this.cache[key] = c;
    return c;
  },

  width(text, scale) {
    return text.length * 6 * scale - scale;
  },

  // align: 'left' | 'center' | 'right'. Draws a drop shadow unless shadow === false.
  draw(ctx, text, x, y, scale, color, align = 'left', shadow = true) {
    text = String(text).toUpperCase();
    const w = this.width(text, scale);
    if (align === 'center') x -= w / 2;
    else if (align === 'right') x -= w;
    x = Math.round(x);
    y = Math.round(y);
    ctx.imageSmoothingEnabled = false;
    for (let i = 0; i < text.length; i++) {
      const gx = x + i * 6 * scale;
      if (shadow) ctx.drawImage(this.glyph(text[i], '#000'), gx + scale, y + scale, 6 * scale, 7 * scale);
      ctx.drawImage(this.glyph(text[i], color), gx, y, 6 * scale, 7 * scale);
    }
  }
};
