"""Beat grid of the background track, used to animate the pianist in time with the music.

Usage: python tools/beats.py [muzik/western in 2026.mp3]    (needs numpy, scipy, soundfile)
Writes js/beats.js with STOMP_BEATS (beat times in seconds) and STOMP_ENERGY (loudness 0..1 per beat).

Steps: decode -> spectral-flux onset envelope -> tempo from autocorrelation ->
dynamic-programming beat tracking (Ellis 2007) -> per-beat loudness.
"""
import sys, io
import numpy as np
import soundfile as sf
from scipy import signal

path = sys.argv[1] if len(sys.argv) > 1 else 'muzik/western in 2026.mp3'
x, sr0 = sf.read(path, always_2d=True)
x = x.mean(axis=1)

# Onset strength: positive log-spectral flux between ~40 Hz and 2.5 kHz, detrended.
y = signal.resample_poly(x, 1, 2); sr = sr0 // 2
hop = 256
_, _, Z = signal.stft(y, fs=sr, nperseg=1024, noverlap=1024 - hop)
flux = np.maximum(0, np.diff(np.log1p(np.abs(Z) * 10), axis=1))
onset = flux[2:120].sum(axis=0)
onset = np.maximum(onset - signal.medfilt(onset, 41), 0)
fps = sr / hop
o = onset / (onset.std() + 1e-9)

# Tempo: strongest autocorrelation peak between 60 and 200 BPM.
ac = np.correlate(o - o.mean(), o - o.mean(), 'full')[len(o) - 1:]
tempos = np.arange(60, 200, 0.5)
bpm0 = tempos[int(np.argmax([ac[int(round(fps * 60 / b))] for b in tempos]))]
print('tempo ~', bpm0, 'BPM')


def track(bpm, tight=100):
    period = fps * 60 / bpm
    n = len(o)
    score = o.copy(); back = np.full(n, -1)
    lo, hi = int(round(period * 0.6)), int(round(period * 1.5))
    for i in range(n):
        a, b = max(0, i - hi), i - lo
        if b < a:
            continue
        prev = np.arange(a, b + 1)
        cand = score[prev] - tight * np.log((i - prev) / period) ** 2
        k = int(np.argmax(cand))
        score[i] = o[i] + cand[k]; back[i] = prev[k]
    end = int(np.argmax(score[-int(period):]) + n - int(period))
    beats = [end]
    while back[beats[-1]] >= 0:
        beats.append(back[beats[-1]])
    return np.array(beats[::-1]) / fps, score[end]


beats, _ = max((track(b) for b in np.arange(bpm0 - 2, bpm0 + 2.1, 0.5)), key=lambda r: r[1])
print(len(beats), 'beats, median interval', np.median(np.diff(beats)).round(4), 's')

# Loudness around each beat, smoothed over 5 beats.
rms = np.array([np.sqrt(np.mean(x[max(0, int((t - .05) * sr0)):int((t + .25) * sr0)] ** 2) or 0) for t in beats])
rms = np.convolve(np.pad(rms, 2, mode='edge'), np.ones(5) / 5, mode='valid')
energy = np.clip(rms / np.percentile(rms, 95), 0, 1)

js = ("// Beat grid of muzik/western in 2026.mp3, generated by tools/beats.py (do not edit).\n"
      "// STOMP_BEATS: beat times in seconds; STOMP_ENERGY: loudness 0..1 at each beat.\n"
      "const STOMP_BEATS = [" + ",".join('%.3f' % t for t in beats) + "];\n"
      "const STOMP_ENERGY = [" + ",".join('%.2f' % v for v in energy) + "];\n")
io.open('js/beats.js', 'w', encoding='utf-8', newline='\n').write(js)
print('wrote js/beats.js', len(js), 'bytes')
