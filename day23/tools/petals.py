# Builds img/petals.png and js/petalatlas.js, an atlas of red rose petals,
# from the CC0 photo "Rose Petals" on StockSnap
# (https://stocksnap.io/photo/rose-petals-BYUXDXPT0I, 960 px version:
# https://cdn.stocksnap.io/img-thumbs/960w/BYUXDXPT0I.jpg).
#
# Usage: python tools/petals.py <photo.jpg>
# Petals are red on a white table: they are cut out by their redness (the
# grey shadows on the table stay out), petals touching the photo border are
# skipped, and each one is scaled into a CELL x CELL square of a grid.
# A normal map is derived from the brightness of the photo (the light on the
# folds and veins of the petal), packed the same way.
import sys, os, io, base64
import numpy as np
from PIL import Image
from scipy import ndimage

CELL = 128
ROOT = os.path.join(os.path.dirname(__file__), '..')
OUT = os.path.join(ROOT, 'img', 'petals.png')
OUT_N = os.path.join(ROOT, 'img', 'petals_n.png')
OUT_JS = os.path.join(ROOT, 'js', 'petalatlas.js')


def main():
    if len(sys.argv) < 2:
        print('usage: petals.py <photo.jpg>')
        sys.exit(1)
    img = Image.open(sys.argv[1]).convert('RGB')
    a = np.asarray(img).astype(np.float32)
    red = a[:, :, 0] - (a[:, :, 1] + a[:, :, 2]) / 2         # redness
    alpha = np.clip((red - 40) / 50, 0, 1)                     # soft edge
    mask = ndimage.binary_opening(alpha > 0.5, iterations=1)
    labels, n = ndimage.label(mask)
    H, W = mask.shape
    petals = []
    for i, sl in enumerate(ndimage.find_objects(labels), 1):
        y0, y1, x0, x1 = sl[0].start, sl[0].stop, sl[1].start, sl[1].stop
        if (y1 - y0) * (x1 - x0) < 600:
            continue
        if y0 <= 1 or x0 <= 1 or y1 >= H - 1 or x1 >= W - 1:
            continue                                            # cut by the photo edge
        pad = 3
        y0, x0 = max(0, y0 - pad), max(0, x0 - pad)
        y1, x1 = min(H, y1 + pad), min(W, x1 + pad)
        own = ndimage.binary_dilation(labels[y0:y1, x0:x1] == i, iterations=pad)
        rgba = np.zeros((y1 - y0, x1 - x0, 4), np.uint8)
        rgba[:, :, :3] = a[y0:y1, x0:x1]
        rgba[:, :, 3] = (alpha[y0:y1, x0:x1] * own * 255).astype(np.uint8)
        petals.append(Image.fromarray(rgba))
    cols = int(np.ceil(np.sqrt(len(petals))))
    rows = int(np.ceil(len(petals) / cols))
    atlas = Image.new('RGBA', (cols * CELL, rows * CELL), (0, 0, 0, 0))
    for k, p in enumerate(petals):
        s = (CELL - 6) / max(p.size)
        p = p.resize((max(1, round(p.width * s)), max(1, round(p.height * s))), Image.LANCZOS)
        atlas.alpha_composite(p, ((k % cols) * CELL + (CELL - p.width) // 2,
                                  (k // cols) * CELL + (CELL - p.height) // 2))
    # Normals: height = brightness (lighter folds stand out), slightly
    # smoothed; Sobel gradients give the tilt. Flat outside the petals.
    rgba = np.asarray(atlas).astype(np.float32)
    al_ = rgba[:, :, 3] / 255
    lum = (0.3 * rgba[:, :, 0] + 0.59 * rgba[:, :, 1] + 0.11 * rgba[:, :, 2]) / 255
    # Extend the brightness past the outline first, or the cut edge would
    # read as a step (a bright ring all around the petal).
    fill = ndimage.gaussian_filter(lum * al_, 4) / np.maximum(ndimage.gaussian_filter(al_, 4), 1e-4)
    hgt = ndimage.gaussian_filter(np.where(al_ > 0.5, lum, fill), 1.2)
    k = 2.6                                                     # bump strength
    gx, gy = ndimage.sobel(hgt, 1) * k, ndimage.sobel(hgt, 0) * k
    n = np.dstack([-gx, gy, np.ones_like(gx)])                  # GL: y up (image y grows down)
    n /= np.linalg.norm(n, axis=2, keepdims=True)
    n = np.where(al_[:, :, None] > 0.3, n, np.array([0, 0, 1.0]))
    nfinal = Image.fromarray(np.clip((n + 1) * 127.5, 0, 255).astype(np.uint8))
    nfinal.save(OUT_N, optimize=True)
    # Colour bleed into transparent pixels, so filtering gives no white fringes.
    arr = np.array(atlas).astype(np.float32)
    al = arr[:, :, 3:4] / 255
    blur_rgb = ndimage.gaussian_filter(arr[:, :, :3] * al, (5, 5, 0))
    blur_a = ndimage.gaussian_filter(al, (5, 5, 0))
    arr[:, :, :3] = np.where(al > 0.5, arr[:, :, :3], blur_rgb / np.maximum(blur_a, 1e-4))
    final = Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))
    final.save(OUT, optimize=True)
    buf = io.BytesIO()
    final.save(buf, 'WEBP', quality=88, method=6)
    data = base64.b64encode(buf.getvalue()).decode('ascii')
    buf = io.BytesIO()
    nfinal.save(buf, 'WEBP', quality=90, method=6)
    ndata = base64.b64encode(buf.getvalue()).decode('ascii')
    with open(OUT_JS, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/petals.py from img/petals.png: red rose petals from\n')
        f.write('// "Rose Petals" on StockSnap (stocksnap.io/photo/rose-petals-BYUXDXPT0I), CC0.\n')
        f.write('// Do not edit by hand.\n')
        f.write('window.PETAL_GRID = { cols: %d, rows: %d, count: %d };\n' % (cols, rows, len(petals)))
        f.write("window.PETAL_ATLAS = 'data:image/webp;base64,%s';\n" % data)
        f.write("window.PETAL_NORMAL = 'data:image/webp;base64,%s';\n" % ndata)
    print('petals:', len(petals), 'grid:', cols, 'x', rows, '+ petalatlas.js', len(data) // 1024, 'KB')


if __name__ == '__main__':
    main()
